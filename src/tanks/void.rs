pub struct VoidBackground {
    pub frames: Vec<Vec<String>>,
    pub current_frame: usize,
    tick_counter: u32,
}

impl VoidBackground {
    pub fn new() -> Self {
        let frames = VOID_FRAMES
            .iter()
            .map(|&f| strip_blank_edges(f.lines().map(|l| l.to_string()).collect()))
            .filter(|f| !f.is_empty())
            .collect();
        Self {
            frames,
            current_frame: 0,
            tick_counter: 0,
        }
    }

    pub fn tick(&mut self) {
        self.tick_counter += 1;
        if self.tick_counter >= VOID_TICKS_PER_FRAME {
            self.tick_counter = 0;
            if !self.frames.is_empty() {
                self.current_frame = (self.current_frame + 1) % self.frames.len();
            }
        }
    }
}

fn strip_blank_edges(lines: Vec<String>) -> Vec<String> {
    let start = match lines.iter().position(|l| !l.trim().is_empty()) {
        Some(i) => i,
        None => return Vec::new(),
    };
    let end = lines.iter().rposition(|l| !l.trim().is_empty()).unwrap() + 1;
    lines[start..end].to_vec()
}
